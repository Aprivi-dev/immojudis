/**
 * Carte de France de l'accueil : un contour léger dessiné en SVG (pas de tuiles, pas de Mapbox), sur
 * lequel les ventes à venir sont posées.
 *
 * Contour : France métropolitaine et Corse, d'après « metropole-version-simplifiee.geojson » du dépôt
 * gregoiredavid/france-geojson, lui-même tiré d'Admin Express (IGN, Licence ouverte Etalab). Projeté
 * en équirectangulaire à 46,6° N (512 × 493 unités, 50 unités par degré de latitude),
 * simplifié (Douglas-Peucker, tolérance 0,8 unité) et arrondi à l'unité : 4,6 Ko.
 */

const WEST_LONGITUDE = -5.25;
const NORTH_LATITUDE = 51.15;
const UNITS_PER_DEGREE = 50;
const LONGITUDE_FACTOR = Math.cos((46.6 * Math.PI) / 180);

export const FRANCE_MAP_WIDTH = 512;
export const FRANCE_MAP_HEIGHT = 493;

/** Position sur la carte (unités du `viewBox`) d'un point donné en degrés. */
export function projectOnFranceMap(latitude: number, longitude: number): { x: number; y: number } {
  return {
    x: (longitude - WEST_LONGITUDE) * LONGITUDE_FACTOR * UNITS_PER_DEGREE,
    y: (NORTH_LATITUDE - latitude) * UNITS_PER_DEGREE,
  };
}

