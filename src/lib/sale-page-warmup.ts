import { resolveSiteOrigin } from "@/lib/site-url";

/** Short on purpose: a warm-up is a courtesy, it never has to wait for a slow page. */
export const WARMUP_TIMEOUT_MS = 5_000;
/** Pages requested at the same time, so that a batch of 100 sales does not hit the site at once. */
export const WARMUP_CONCURRENCY = 4;
/**
 * Pages warmed per call at most: the warm-up runs in `after()`, inside the function's time
 * budget (`maxDuration = 60` on `revalidate-sale`). 32 pages at 4 at a time make 8 rounds of 5 s at
 * most, that is 40 s in the worst case, which leaves 20 s for what runs before (the lookup of the
 * tribunal pages and the regeneration of the court activity). It was 24 (30 s) before the catalogue
 * pages 2 and 3, the upcoming hearings and the tribunal pages joined the warm-up; the cap is the
 * budget, not the number of sales: the other pages of a larger batch are rendered by their first
 * visitor, as before.
 */
export const MAX_WARMUP_PAGES = 32;

export type SalePageWarmupSummary = {
  requested: number;
  warmed: number;
  failed: number;
  skipped?: "origin-not-configured" | "origin-invalid";
};

type WarmupOptions = {
  env?: Readonly<Record<string, string | undefined>>;
  fetchImpl?: typeof fetch;
  timeoutMs?: number;
  concurrency?: number;
  log?: (entry: Record<string, unknown>) => void;
  requestId?: string;
  /**
   * Public paths to warm in addition to the sale pages, requested first so that the page cap never
   * drops them (e.g. `/sales`, which the proxy rewrites to the static page `/sales/defaut`: the
   * internal address itself redirects, so the public one is the one to request).
   */
  extraPaths?: readonly string[];
};

type WarmupTarget = { path: string; saleId?: string };

/**
 * Requests the public page of each sale once, right after the pipeline expired it, so that the
 * first visitor (often a crawler) finds a freshly generated page instead of paying for the
 * regeneration.
 *
 * - One `GET /sales/<id>` per sale (and one per extra path, e.g. `/sales`), on the public origin (`resolveSiteOrigin`, the production
 *   domain on Vercel), with a short time limit. The page is a plain read: it never calls
 *   `revalidate-sale` back, so there is no loop, and no request is repeated or retried.
 * - Never throws: a failure is logged and the warm-up goes on (the page is then generated by the
 *   first real visit, as before).
 * - Meant to run after the response has been sent (`after()`), never to block it.
 */
export async function warmSalePages(
  saleIds: readonly string[],
  options: WarmupOptions = {},
): Promise<SalePageWarmupSummary> {
  const log = options.log ?? defaultLog;
  const ids = [...new Set(saleIds.map((id) => id.toLowerCase()))];
  const targets: WarmupTarget[] = [
    ...[...new Set(options.extraPaths ?? [])].map((path) => ({ path })),
    ...ids.map((id) => ({ path: `/sales/${id}`, saleId: id })),
  ].slice(0, MAX_WARMUP_PAGES);
  const summary: SalePageWarmupSummary = { requested: targets.length, warmed: 0, failed: 0 };
  if (targets.length === 0) return summary;

  let origin: string | null;
  try {
    origin = resolveSiteOrigin(options.env ?? process.env);
  } catch {
    log({ event: "skipped", reason: "origin-invalid", requested: targets.length });
    return { ...summary, skipped: "origin-invalid" };
  }
  if (!origin) {
    log({ event: "skipped", reason: "origin-not-configured", requested: targets.length });
    return { ...summary, skipped: "origin-not-configured" };
  }

  const fetchImpl = options.fetchImpl ?? fetch;
  const timeoutMs = options.timeoutMs ?? WARMUP_TIMEOUT_MS;
  const queue = [...targets];

  async function warmOne({ path, saleId }: WarmupTarget) {
    const startedAt = Date.now();
    try {
      const response = await fetchImpl(`${origin}${path}`, {
        method: "GET",
        headers: { "user-agent": "Immojudis-cache-warmup", accept: "text/html" },
        cache: "no-store",
        signal: AbortSignal.timeout(timeoutMs),
      });
      // Read to the end: the answer is complete only once the page is generated and streamed.
      await response.arrayBuffer();
      // Only a 2xx or a 404 means the page was generated: a 404 is a valid answer for a sale that
      // left the catalogue (cached as such). Anything else (401, 403, 429, 3xx, 5xx) is a page that
      // was not warmed, whatever the reason (firewall, rate limit, redirect, error).
      const ok = (response.status >= 200 && response.status < 300) || response.status === 404;
      if (ok) summary.warmed += 1;
      else summary.failed += 1;
      log({
        event: ok ? "warmed" : "failed",
        path,
        saleId,
        status: response.status,
        cache: response.headers.get("x-vercel-cache"),
        ms: Date.now() - startedAt,
        requestId: options.requestId,
      });
    } catch (error) {
      summary.failed += 1;
      log({
        event: "failed",
        path,
        saleId,
        error: error instanceof Error ? error.name : "unknown",
        ms: Date.now() - startedAt,
        requestId: options.requestId,
      });
    }
  }

  const workers = Math.max(1, Math.min(options.concurrency ?? WARMUP_CONCURRENCY, targets.length));
  await Promise.all(
    Array.from({ length: workers }, async () => {
      for (let target = queue.shift(); target !== undefined; target = queue.shift())
        await warmOne(target);
    }),
  );
  log({ event: "done", ...summary, requestId: options.requestId });
  return summary;
}

function defaultLog(entry: Record<string, unknown>) {
  const line = JSON.stringify({ scope: "sale-page-warmup", ...entry });
  if (entry.event === "failed" || entry.event === "skipped") console.warn(line);
  else console.info(line);
}
