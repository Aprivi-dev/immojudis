create table public.information_agent_email_templates (
  id uuid primary key default gen_random_uuid(),
  revision bigint generated by default as identity unique,
  name text not null default 'Demande d’informations' check (
    char_length(name) between 3 and 120
  ),
  status text not null default 'draft' check (
    status in ('draft', 'published', 'archived')
  ),
  subject_template text not null check (
    char_length(subject_template) between 3 and 200
    and subject_template !~ E'[\\r\\n]'
  ),
  blocks jsonb not null check (
    jsonb_typeof(blocks) = 'array'
    and jsonb_array_length(blocks) between 1 and 12
    and pg_column_size(blocks) <= 32768
  ),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'published' and published_at is not null)
    or status <> 'published'
  )
);

create unique index information_agent_email_templates_one_published_idx
  on public.information_agent_email_templates ((status))
  where status = 'published';
create unique index information_agent_email_templates_one_draft_idx
  on public.information_agent_email_templates ((status))
  where status = 'draft';
create index information_agent_email_templates_history_idx
  on public.information_agent_email_templates (revision desc, created_at desc);

