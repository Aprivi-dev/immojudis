create or replace function public.publish_information_agent_email_template(
  p_template_id uuid,
  p_admin_id uuid
)
returns public.information_agent_email_templates
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_template public.information_agent_email_templates%rowtype;
begin
  if not exists (
    select 1
    from public.user_profiles profile
    where profile.user_id = p_admin_id
      and profile.user_role = 'admin'
  ) then
    raise exception using errcode = '42501', message = 'Administrator access required.';
  end if;

  select * into v_template
  from public.information_agent_email_templates template
  where template.id = p_template_id
  for update;

  if v_template.id is null or v_template.status <> 'draft' then
    raise exception using errcode = '55000', message = 'A draft template is required.';
  end if;

  update public.information_agent_email_templates
  set status = 'archived',
      updated_by = p_admin_id,
      updated_at = statement_timestamp()
  where status = 'published';

  update public.information_agent_email_templates
  set status = 'published',
      published_by = p_admin_id,
      published_at = statement_timestamp(),
      updated_by = p_admin_id,
      updated_at = statement_timestamp()
  where id = p_template_id
  returning * into v_template;

  return v_template;
end;
$$;

