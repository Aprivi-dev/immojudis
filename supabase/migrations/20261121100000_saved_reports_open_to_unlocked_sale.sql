-- Le déblocage d'une vente ouvre toute l'offre Analyse sur cette vente, rapport enregistré compris
-- (décision du propriétaire du 15/11/2026, lot 2).
--
-- public.saved_property_reports porte la politique RESTRICTIVE analysis_access_required (20260710083858) :
-- un compte ne lisait ses rapports enregistrés qu'avec l'accès Analyse. Elle devient :
--   accès Analyse
--   OU (vente du rapport débloquée par le compte (app_private.current_user_unlocked_sale)
--       ET aperçu du rapport construit par la porte déblocage : report_snapshot ->> 'door' = 'unlock').
-- La seconde condition ferme les anciennes lignes de la vente débloquée (par exemple un rapport enregistré
-- pendant un essai, avec l'accès Analyse) : leur aperçu porte le score d'investissement et les sources, que
-- le déblocage n'ouvre pas. Seul l'aperçu construit pour la porte déblocage (buildReportSnapshot,
-- src/lib/property-report/analysis.ts, clé « door ») se limite à ce que le déblocage ouvre ; le serveur
-- applique la même règle (reportOpenThrough, src/lib/property-reports.ts).
-- Rien d'autre ne change :
--   * les politiques permissives (20260706112000) limitent toujours la lecture aux rapports du compte
--     (ou à l'administrateur) : la politique restrictive s'y ajoute, elle n'ouvre jamais le rapport d'un
--     autre compte ;
--   * authenticated n'a que SELECT sur la table (20260714162932) : les rapports sont écrits par le serveur
--     (client de service). Le with check reprend la même condition, comme la politique d'origine ;
--   * un déblocage qui ne compte plus (vente hors ligne, plus de 24 mois) ne donne plus accès au rapport :
--     current_user_unlocked_sale porte déjà ces deux règles ;
--   * public.property_report_exports garde sa politique (accès Analyse seul) : la table n'est écrite que
--     par le client de service (src/lib/property-report/repository.ts) et n'est lue par aucune session ;
--   * ni public.v_auction_sales_unlocked ni les politiques des tables enfants des ventes (auction_documents,
--     auction_risks, ...) ne sont touchées : auction_sales n'est pas ouverte à un déblocage.
--
-- has_analysis_access() est encapsulée dans un sous-select (InitPlan, une évaluation par requête, comme
-- 20261029170200) ; current_user_unlocked_sale et la clé « door » dépendent de la ligne, elles sont évaluées
-- par ligne.
--
-- Verrous : remplacement d'une politique sur saved_property_reports (verrou bref de la table).
begin;

set local lock_timeout = '5s';

drop policy if exists analysis_access_required on public.saved_property_reports;
create policy analysis_access_required on public.saved_property_reports
as restrictive
for all
to authenticated
using (
  (select public.has_analysis_access())
  or (
    app_private.current_user_unlocked_sale(sale_id)
    and (report_snapshot ->> 'door') = 'unlock'
  )
)
with check (
  (select public.has_analysis_access())
  or (
    app_private.current_user_unlocked_sale(sale_id)
    and (report_snapshot ->> 'door') = 'unlock'
  )
);

comment on policy analysis_access_required on public.saved_property_reports is
  'Restrictive: a saved report is readable with the Analyse access, or when the account unlocked its sale (app_private.current_user_unlocked_sale) AND the report snapshot was built through the unlock door (report_snapshot ->> ''door'' = ''unlock''). ANDed with the owner policies: never another account''s report.';

comment on table public.saved_property_reports is
  'User-owned opportunity reports generated by ImmoJudis for judicial-sale analysis, PDF export and report editing features. Readable by the owner with the Analyse access, or, for a sale the owner unlocked, when its snapshot was built through the unlock door (policy analysis_access_required, 20261121100000). Written by the server only.';

comment on function app_private.current_user_unlocked_sale(uuid) is
  'True when the signed-in account unlocked this sale (one unlock in all for Découverte), less than 24 months ago, and the sale is still online. Used by get_sale_unlock_status, v_auction_sales_unlocked and the restrictive policy analysis_access_required of saved_property_reports.';

notify pgrst, 'reload schema';

commit;
